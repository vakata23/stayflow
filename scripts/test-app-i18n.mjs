// Превод на приложението на собственика (гръцки, македонски): покритие и коректност на речниците и на превеждача.
//   node scripts/test-app-i18n.mjs
// Покритието се мери срещу самия код: извлича се всеки български текст от екраните (scripts/i18n/extract-app-strings.mjs)
// и за него трябва да има превод — нов екран с нов български текст без превод проваля теста.
import { readFileSync } from 'node:fs'
import { extractAll } from './i18n/extract-app-strings.mjs'
import { createTranslator } from '../src/i18n/translator.js'
import el from '../src/i18n/el.js'
import mk from '../src/i18n/mk.js'

let pass = 0
let fail = 0
const ok = (name, cond, extra = '') => {
  if (cond) pass++
  else {
    fail++
    console.log('  ПРОВАЛ:', name, extra)
  }
}

const CYR = /[Ѐ-ӿ]/
const GREEK = /[Ͱ-Ͽ]/
const BG_ONLY = /[ъщюяыэё]/i // букви, които ги има в българския, а в македонския — не
const placeholders = (s) => (s.match(/\{\d+\}/g) ?? []).sort().join(',')

const found = extractAll()
const texts = found.map((e) => e.text)
ok('има над 800 български текста за превод', texts.length > 800, String(texts.length))

for (const [code, dict] of [['el', el], ['mk', mk]]) {
  const missing = texts.filter((t) => !(t in dict) || !dict[t])
  ok(`${code}: има превод за всеки български текст от екраните (${texts.length})`, missing.length === 0, `липсват ${missing.length}: ${missing.slice(0, 8).join(' | ')}`)
  const badVars = texts.filter((t) => t in dict && placeholders(t) !== placeholders(dict[t]))
  ok(`${code}: {0}, {1}… са същите като в оригинала`, badVars.length === 0, badVars.slice(0, 5).join(' | '))
  const stale = Object.keys(dict).filter((k) => !texts.includes(k))
  // заглавие на страницата, слепеното изречение за почистването и шаблоните за сглобени в кода текстове (описание на правило, „5-о число“)
  ok(`${code}: освен текстовете от кода има само 7 допълнителни записа`, stale.length === 7, stale.map((s) => s.slice(0, 40)).join(' | '))
  ok(`${code}: няма празни и недокоснати преводи с интервали накрая`, Object.values(dict).every((v) => v && v === v.trim() || /^[\s\S]*[ ,.]$/.test(v) === false))
}

/* азбука: гръцкият без кирилица (освен примера с „Морски апартамент“), македонският без български букви */
const ELLIPSIS_OK = (k) => /Морски апартамент/.test(k)
const elCyr = Object.entries(el).filter(([k, v]) => CYR.test(v) && !ELLIPSIS_OK(k))
ok('el: няма останала кирилица в преводите', elCyr.length === 0, elCyr.slice(0, 5).map(([k, v]) => v).join(' | '))
const elNoGreek = Object.entries(el).filter(([k, v]) => /[Ѐ-ӿa-z]/i.test(k) && !GREEK.test(v) && !/^[\x00-\x7F€…\s]*$/.test(v))
ok('el: всеки превод е на гръцка азбука', elNoGreek.length === 0, elNoGreek.slice(0, 5).map(([, v]) => v).join(' | '))
const mkBg = Object.entries(mk).filter(([, v]) => BG_ONLY.test(v))
ok('mk: няма български букви (ъ щ ю я) в македонските преводи', mkBg.length === 0, mkBg.slice(0, 5).map(([, v]) => v).join(' | '))
ok('mk: преводите са на кирилица', Object.entries(mk).filter(([k, v]) => CYR.test(k) && !CYR.test(v) && !/^[\x00-\x7F€…\s]*$/.test(v)).length === 0)

/* ключови термини — еднакви навсякъде */
const term = (dict, bg) => dict[bg]
ok('el: основното меню (Табло, Календар, Резервации, Приходи, Ценови планове, Известия)', ['Табло', 'Календар', 'Резервации', 'Приходи', 'Ценови планове', 'Известия'].map((k) => term(el, k)).join('|') === 'Πίνακας ελέγχου|Ημερολόγιο|Κρατήσεις|Έσοδα|Τιμολογιακά πλάνα|Ειδοποιήσεις')
ok('mk: основното меню (Табло, Календар, Резервации, Приходи, Ценови планове, Известия)', ['Табло', 'Календар', 'Резервации', 'Приходи', 'Ценови планове', 'Известия'].map((k) => term(mk, k)).join('|') === 'Табла|Календар|Резервации|Приходи|Ценовни планови|Известувања')
ok('месеците са във всички езици (12) и дните (7)', ['Януари', 'Февруари', 'Март', 'Април', 'Май', 'Юни', 'Юли', 'Август', 'Септември', 'Октомври', 'Ноември', 'Декември', 'Пн', 'Вт', 'Ср', 'Чт', 'Пт', 'Сб', 'Нд'].every((k) => el[k] && mk[k]))
const indexHtml = readFileSync(new URL('../index.html', import.meta.url), 'utf8')
const title = /<title>([^<]+)<\/title>/.exec(indexHtml)?.[1]
ok('заглавието на страницата от index.html има превод', title && el[title] && mk[title], title)

/* превеждачът */
const tEl = createTranslator(el)
const tMk = createTranslator(mk)
ok('точен текст: „Запази“', tEl.translate('Запази') === 'Αποθήκευση' && tMk.translate('Запази') === 'Зачувај')
ok('интервалите около текста се запазват (възел „ Запази “)', tEl.translate('  Запази ') === '  Αποθήκευση ' && tEl.translate('\nЗапази') === '\nΑποθήκευση')
ok('нов ред и двойни интервали вътре се събират', tEl.translate('Няма   добавени\nимоти') === 'Δεν έχουν προστεθεί ακίνητα')
ok('текст без кирилица не се пипа (число, €, Telegram)', tEl.translate('87.00 €') === '87.00 €' && tMk.translate('Telegram') === 'Telegram' && tEl.translate('') === '')
ok('непознат български текст остава непроменен', tEl.translate('Нещо, което го няма в речника') === 'Нещо, което го няма в речника' && tMk.translate('Нещо ново') === 'Нещо ново')
ok('шаблон с име: „Импортирана от Airbnb“', tEl.translate('Импортирана от Airbnb') === 'Εισήχθη από Airbnb' && tMk.translate('Импортирана от Booking.com') === 'Увезена од Booking.com')
ok('шаблон с няколко места: „Етикетирани: 3 от 12. Всички са отбелязани.“ (вложен превод на {2})', tEl.translate('Етикетирани: 3 от 12. Всички са отбелязани.') === 'Με ετικέτα: 3 από 12. Όλες έχουν σημειωθεί.' && tMk.translate('Етикетирани: 3 от 12. Всички са отбелязани.') === 'Означени: 3 од 12. Сите се означени.')
ok('шаблон с дата: „Настанен · до 25.10.2026“', tEl.translate('Настанен · до 25.10.2026') === 'Φιλοξενείται · έως 25.10.2026' && tMk.translate('Настанен · до 25.10.2026') === 'Сместен · до 25.10.2026')
ok('шаблон с брой: „Следващите 14 дни“', tEl.translate('Следващите 14 дни') === 'Επόμενες 14 ημέρες' && tMk.translate('Следващите 14 дни') === 'Следните 14 дена')
ok('шаблон „{0} от {1} {2}“ превежда и думата накрая („2 от 3 имота“)', tEl.translate('2 от 3 имота') === '2 από 3 ακίνητα' && tMk.translate('2 от 3 имота') === '2 од 3 имоти')
ok('кратък шаблон не лапа случайно изречение („Задайте новата си парола от тук сега“ остава)', tEl.translate('Задайте новата си парола от тук сега') === 'Задайте новата си парола от тук сега')
ok('съобщение със системен текст отзад: „Неуспешно записване: duplicate key“', tEl.translate('Неуспешно записване: duplicate key') === 'Αποτυχία αποθήκευσης: duplicate key' && tMk.translate('Неуспешно записване: JWT expired') === 'Неуспешно зачувување: JWT expired')
ok('„Неуспешно записване:“ не се лепи към друга дума („Неуспешно записванее“)', tEl.translate('Неуспешно записванее') === 'Неуспешно записванее')
ok('месец и година: „Октомври“ и „2026“ (отделни възли)', tEl.translate('Октомври') === 'Οκτώβριος' && tMk.translate('Октомври') === 'Октомври' && tMk.translate('Ноември') === 'Ноември')
ok('шаблон „{0}: директни {1}, платформи {2}“ (аria-label на графика)', tEl.translate('Окт 26: директни 120 €, платформи 80 €') === 'Окт 26: άμεσες 120 €, πλατφόρμες 80 €')
ok('слепеното изречение за почистването се превежда цялото', tEl.translate('Таксата за почистване, която плаща гостът, вече е в цената на резервацията (в „Приходи“). Тук въвеждате само това, което ВИЕ плащате за почистване — не го добавяйте и като приход.').startsWith('Η χρέωση καθαρισμού'))
ok('повторен превод на готов гръцки текст не го променя', tEl.translate('Αποθήκευση') === 'Αποθήκευση' && tEl.translate(tEl.translate('Запази')) === 'Αποθήκευση')
ok('сглобен текст се превежда по фрази: „Почистване 25 € на резервация“', tEl.translate('Почистване 25 € на резервация') === 'Καθαρισμός 25 € ανά κράτηση' && tMk.translate('Закуска 8 € на нощувка') === 'Појадок 8 € по ноќевање')
ok('сглобен текст с разделител отпред: „· Почистване“', tEl.translate('· Почистване') === '· Καθαρισμός' && tMk.translate('· Почистване') === '· Чистење')
ok('число и сума в шаблон: „10 резервации · нето 3370.25 €“', tEl.translate('10 резервации · нето 3370.25 €') === '10 κρατήσεις · καθαρό 3370.25 €')
ok('имена и бележки на потребителя не се пипат (име на имот, гост, смесен текст)', ['Студио „Морски бриз“', 'Мария Петрова', 'Мария Петрова · Приход', 'Георги Димитров · Студио „Морски бриз“', 'Сметка за септември'].every((t) => tEl.translate(t) === t && tMk.translate(t) === t))
ok('обем: речникът за превеждача е пълен (над 800 записа)', tEl.size > 800 && tMk.size > 800, `${tEl.size}/${tMk.size}`)

/* всеки текст от кода се превежда от самия превеждач (не само „е в речника“) — и дава различен резултат за гръцки */
let notTranslatedEl = 0
for (const text of texts) {
  const concrete = text.replace(/\{\d+\}/g, '5') // шаблонът с примерна стойност, както ще стигне до възела
  if (tEl.translate(concrete) === concrete) notTranslatedEl++
}
ok('гръцки: превеждачът превежда всеки текст от екраните (с примерни стойности на {n})', notTranslatedEl === 0, `${notTranslatedEl} не се превеждат`)
let notTranslatedMk = 0
const sameInMk = []
for (const text of texts) {
  const concrete = text.replace(/\{\d+\}/g, '5')
  const out = tMk.translate(concrete)
  if (out === concrete && mk[text] !== text) notTranslatedMk++
  if (out === concrete) sameInMk.push(text)
}
ok('македонски: превеждачът не изпуска нито един текст, чийто превод е различен', notTranslatedMk === 0, `${notTranslatedMk} не се превеждат`)

console.log(`test-app-i18n: ${pass} успешни, ${fail} провалени (текстове в кода: ${texts.length}; еднакви на български и македонски: ${sameInMk.length})`)
process.exit(fail ? 1 : 0)
